const DEFAULT_URL = `postgres://${process.env.USER ?? "postgres"}@localhost:5432/dataminer`;
const databaseUrl = process.env.DATABASE_URL?.trim() || DEFAULT_URL;

let _db: PostgresJsDatabase | null = null;
let _client: postgres.Sql | null = null;
let _ready: Promise<void> | null = null;

export function getDb(): PostgresJsDatabase {
  if (!_db) {
    _client = postgres(databaseUrl, { max: 10, idle_timeout: 20, connect_timeout: 10 });
    _db = drizzle(_client);
  }
  return _db;
}

/** Ensures schema exists. Uses generated migrations when present, otherwise pushes schema. */
async function ensureSchema(client: postgres.Sql): Promise<void> {
  const migrationsDir = path.join(process.cwd(), "drizzle");
  const db = drizzle(client);
  if (fs.existsSync(path.join(migrationsDir, "meta", "_journal.json"))) {
    await migrate(db, { migrationsFolder: migrationsDir });
  } else {
    await client.unsafe(`
      CREATE TABLE IF NOT EXISTS cases (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        ai_columns JSONB NOT NULL DEFAULT '[]'::jsonb,
        api_key TEXT,
        cerebras_api_key TEXT,
        anthropic_api_key TEXT,
        eden_api_key TEXT,
        eden_region TEXT NOT NULL DEFAULT 'eu',
        model_allowlist JSONB NOT NULL DEFAULT '[]'::jsonb,
        col_order JSONB NOT NULL DEFAULT '[]'::jsonb,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
      );

      CREATE TABLE IF NOT EXISTS rows (
        id TEXT PRIMARY KEY,
        case_id TEXT NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
        row_index INTEGER NOT NULL,
        data JSONB NOT NULL DEFAULT '{}'::jsonb,
        cell_statuses JSONB NOT NULL DEFAULT '{}'::jsonb,
        cell_errors JSONB NOT NULL DEFAULT '{}'::jsonb,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
      );
      CREATE INDEX IF NOT EXISTS idx_rows_case_id ON rows(case_id, row_index);

      CREATE TABLE IF NOT EXISTS logs (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        case_id TEXT NOT NULL,
        message TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL
      );
      CREATE INDEX IF NOT EXISTS idx_logs_case_id ON logs(case_id, id DESC);

      CREATE TABLE IF NOT EXISTS scrape_cache (
        url TEXT PRIMARY KEY,
        markdown TEXT NOT NULL,
        title TEXT,
        fetched_at TIMESTAMPTZ NOT NULL
      );

      CREATE TABLE IF NOT EXISTS apollo_cache (
        lookup_key TEXT PRIMARY KEY,
        payload JSONB NOT NULL,
        fetched_at TIMESTAMPTZ NOT NULL
      );

      CREATE TABLE IF NOT EXISTS settings (
        id TEXT PRIMARY KEY DEFAULT 'global',
        eden_api_key TEXT,
        eden_region TEXT NOT NULL DEFAULT 'eu',
        updated_at TIMESTAMPTZ NOT NULL
      );

      CREATE TABLE IF NOT EXISTS agent_runs (
        id TEXT PRIMARY KEY,
        case_id TEXT NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
        goal JSONB NOT NULL,
        status TEXT NOT NULL DEFAULT 'planning',
        state JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
      );
      CREATE INDEX IF NOT EXISTS idx_agent_runs_case_id ON agent_runs(case_id);
    `);
  }
}

/** Call once before any DB access (idempotent). */
export async function initDb(): Promise<void> {
  if (_ready) return _ready;
  getDb();
  _ready = ensureSchema(_client!).catch((e) => {
    _ready = null;
    throw e;
  });
  return _ready;
}

// ── Serialization helpers ────────────────────────────────────────────────────

function toIso(v: unknown): string {
  return v instanceof Date ? v.toISOString() : String(v ?? new Date().toISOString());
}

type CaseRow = typeof cases.$inferSelect;
type RowRow = typeof rows.$inferSelect;

function deserializeCase(row: CaseRow): Case {
  const edenApiKey = decryptSecret(row.edenApiKey ?? undefined);
  return {
    id: row.id,
    name: row.name,
    aiColumns: (row.aiColumns ?? []) as Case["aiColumns"],
    edenApiKey,
    edenApiKeyMasked: maskSecret(edenApiKey),
    edenRegion: row.edenRegion === "eu" ? "eu" : "us",
    modelAllowlist: (row.modelAllowlist ?? []) as string[],
    colOrder: (row.colOrder ?? []) as string[],
    createdAt: toIso(row.createdAt),
    updatedAt: toIso(row.updatedAt),
  };
}

function deserializeRow(row: RowRow): RowData {
  return {
    id: row.id,
    caseId: row.caseId,
    rowIndex: row.rowIndex,
    data: (row.data ?? {}) as RowData["data"],
    cellStatuses: (row.cellStatuses ?? {}) as RowData["cellStatuses"],
    cellErrors: (row.cellErrors ?? {}) as RowData["cellErrors"],
    createdAt: toIso(row.createdAt),
    updatedAt: toIso(row.updatedAt),
  };
}

