export async function bulkInsertRows(newRows: RowData[]): Promise<void> {
  if (newRows.length === 0) return;
  await initDb();
  // All-or-nothing: chunked inserts run inside a single transaction
  await getDb().transaction(async (tx) => {
    await bulkInsertRowsWith(tx as unknown as PostgresJsDatabase, newRows);
  });
}

async function bulkInsertRowsWith(executor: PostgresJsDatabase, newRows: RowData[]): Promise<void> {
  if (newRows.length === 0) return;
  const now = new Date();
  // Chunk to stay within statement size limits
  const CHUNK = 500;
  for (let i = 0; i < newRows.length; i += CHUNK) {
    const chunk = newRows.slice(i, i + CHUNK);
    const values = chunk.map((r) => ({
      id: r.id,
      caseId: r.caseId,
      rowIndex: r.rowIndex,
      data: r.data ?? {},
      cellStatuses: r.cellStatuses ?? {},
      cellErrors: r.cellErrors ?? {},
      createdAt: new Date(r.createdAt || now),
      updatedAt: now,
    }));
    await executor
      .insert(rows)
      .values(values)
      .onConflictDoUpdate({
        target: rows.id,
        // mirror old SQLite behaviour: conflicting rows get fresh data
        set: { data: sql`excluded.data`, updatedAt: sql`excluded.updated_at` },
      });
  }
}

// ── Discovery helpers ────────────────────────────────────────────────────────

/** Highest row_index in a case (-1 when empty). Used to append discovered rows. */
export async function getMaxRowIndex(caseId: string): Promise<number> {
  await initDb();
  return getMaxRowIndexWith(getDb(), caseId);
}

async function getMaxRowIndexWith(executor: PostgresJsDatabase, caseId: string): Promise<number> {
  const result = await executor
    .select({ maxIdx: sql<number | null>`MAX(${rows.rowIndex})` })
    .from(rows)
    .where(eq(rows.caseId, caseId));
  const v = result[0]?.maxIdx;
  return v == null ? -1 : Number(v);
}

/**
 * All normalised domains already present in a case. Every row may contribute
 * MULTIPLE domains — `source_domain`, `official_domain` and `domain` are all
 * collected (one row can legitimately know a company under several domains).
 * Uses PG unnest + jsonb operators — no full-row transfer needed.
 */
export async function getExistingDomains(caseId: string): Promise<string[]> {
  await initDb();
  return getExistingDomainsWith(getDb(), caseId);
}

async function getExistingDomainsWith(executor: PostgresJsDatabase, caseId: string): Promise<string[]> {
  const raw = await executor.execute(sql`
    SELECT DISTINCT LOWER(
      REGEXP_REPLACE(
        REGEXP_REPLACE(
          REGEXP_REPLACE(v.val, '^https?://', ''),
          '^www\\.', ''
        ), '/.*$', ''
      )
    ) AS domain
    FROM ${rows},
    LATERAL unnest(ARRAY[
      ${rows.data}->>'source_domain',
      ${rows.data}->>'official_domain',
      ${rows.data}->>'domain'
    ]) AS v(val)
    WHERE ${rows.caseId} = ${caseId} AND v.val IS NOT NULL AND v.val <> ''
  `);
  // postgres-js returns the row list directly; normalise defensively
  const arr: unknown[] = Array.isArray(raw) ? raw : ((raw as { rows?: unknown[] }).rows ?? []);
  const domains = new Set<string>();
  for (const r of arr as Array<{ domain: string | null }>) {
    const d = String(r.domain ?? "").trim();
    if (d.includes(".")) domains.add(d);
  }
  return Array.from(domains);
}

/**
 * Append discovery seed rows to a case, skipping duplicate domains (both
 * against existing rows and within the batch). Runs in a single transaction
 * holding a FOR UPDATE lock on the parent case so two concurrent discovery
 * imports cannot both pass the duplicate check (no race-written duplicates).
 */
export async function appendDiscoveryRows(
  caseId: string,
  seeds: RowData[]
): Promise<{ inserted: number; duplicates: number }> {
  await initDb();
  const db = getDb();
  return await db.transaction(async (tx) => {
    const executor = tx as unknown as PostgresJsDatabase;
    await executor.execute(sql`SELECT id FROM ${cases} WHERE id = ${caseId} FOR UPDATE`);

    const existingDomains = new Set(await getExistingDomainsWith(executor, caseId));

    // Also load existing _parent_row_id values to avoid duplicate contact rows
    const existingRows = await executor.select({ data: rows.data }).from(rows)
      .where(eq(rows.caseId, caseId));
    const existingParentIds = new Set(
      existingRows
        .map(r => (r.data as Record<string, string>)["_parent_row_id"])
        .filter(Boolean)
    );

    const maxIdx = await getMaxRowIndexWith(executor, caseId);
    let duplicates = 0;
    const toInsert: RowData[] = [];
    let nextIdx = maxIdx + 1;

    for (const seed of seeds) {
      const data = seed.data as Record<string, string>;

      // Check for contact row duplicate by parent
      if (data["_parent_row_id"] && existingParentIds.has(data["_parent_row_id"])) {
        duplicates++;
        continue;
      }

      // Check domain duplicate (try both domain and source_domain fields)
      const domain = (data["domain"] ?? data["source_domain"] ?? "").toLowerCase().trim();
      if (domain && existingDomains.has(domain)) {
        duplicates++;
        continue;
      }

      if (domain) existingDomains.add(domain);
      if (data["_parent_row_id"]) existingParentIds.add(data["_parent_row_id"]);
      toInsert.push({ ...seed, rowIndex: nextIdx++ });
    }

    if (toInsert.length > 0) await bulkInsertRowsWith(executor, toInsert);
    return { inserted: toInsert.length, duplicates };
  });
}

