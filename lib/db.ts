/**
 * lib/db.ts
 * PostgreSQL data layer via Drizzle ORM (postgres-js driver).
 *
 * LOCAL: brew services postgresql@17 + DATABASE_URL=postgres://<user>@localhost:5432/dataminer
 * CLOUD: any Postgres URL works unchanged (Neon, Supabase, RDS…).
 *
 * Schema is auto-pushed on first connection (drizzle push, safe/idempotent for dev).
 * All functions are async (postgres drivers are async by nature).
 */

