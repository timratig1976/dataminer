/**
 * Update a single key inside a row's JSONB data + statuses without a read-modify-write
 * round trip (atomic, concurrency-safe — important for parallel column runs).
 */
export async function updateRowCell(rowId: string, outputKey: string, value: string, status: string, error?: string): Promise<void> {
  await initDb();
  const db = getDb();
  // Explicit ::text casts on the key params — Postgres cannot infer parameter
  // types inside jsonb_build_object from bind placeholders alone.
  await db
    .update(rows)
    .set({
      data: sql`${rows.data} || jsonb_build_object(${outputKey}::text, ${value}::text)`,
      cellStatuses: sql`${rows.cellStatuses} || jsonb_build_object(${outputKey}::text, ${status}::text)`,
      cellErrors: sql`CASE WHEN ${error ?? null}::text IS NULL
        THEN ${rows.cellErrors} - ${outputKey}::text
        ELSE ${rows.cellErrors} || jsonb_build_object(${outputKey}::text, ${error ?? ""}::text) END`,
      updatedAt: new Date(),
    })
    .where(eq(rows.id, rowId));
}

