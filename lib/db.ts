export async function createCase(c: Omit<Case, "createdAt" | "updatedAt">): Promise<Case> {
  await initDb();
  const now = new Date();
  await getDb()
    .insert(cases)
    .values({
      id: c.id,
      name: c.name,
      aiColumns: c.aiColumns ?? [],
      edenApiKey: encryptSecret(c.edenApiKey),
      edenRegion: c.edenRegion ?? "us",
      modelAllowlist: c.modelAllowlist ?? [],
      colOrder: c.colOrder ?? [],
      createdAt: now,
      updatedAt: now,
    });
  return (await getCase(c.id))!;
}

export async function updateCase(id: string, patch: Partial<Omit<Case, "id" | "createdAt">>): Promise<Case | null> {
  await initDb();
  const existing = await getCase(id);
  if (!existing) return null;
  const merged = { ...existing, ...patch, updatedAt: new Date().toISOString() };
  await getDb()
    .update(cases)
    .set({
      name: merged.name,
      aiColumns: merged.aiColumns ?? [],
      edenApiKey: encryptSecret(merged.edenApiKey),
      edenRegion: merged.edenRegion ?? "us",
      modelAllowlist: merged.modelAllowlist ?? [],
      colOrder: merged.colOrder ?? [],
      updatedAt: new Date(merged.updatedAt),
    })
    .where(eq(cases.id, id));
  return (await getCase(id))!;
}

